def _atomic(path, write):
    """write(tmp_path) then rename, so a reader never sees half a file."""
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.stem}.tmp{os.getpid()}{path.suffix}")
    write(tmp)
    os.replace(tmp, path)


def views_path(crop_id, pert=P0):
    return VIEWS_DIR / pert / f"{crop_id}.npz"


def build_views(crop_id, pert=P0, force=False):
    """Make and store one crop version. Perturbations and injections are applied to the RAW image, then harmonised."""
    path = views_path(crop_id, pert)
    if path.exists() and not force:
        return path
    folder = crops_table().set_index("site").folder[crop_id]
    raw = {d: load_grey(raw_path(folder, crop_id, d)) for d in ("BSE", "Inlens", "SE")}
    r0, r1, x0, x1 = common_window(raw["BSE"].shape)
    seed = zlib.crc32(np.ascontiguousarray(raw["BSE"][r0:r1, x0:x1]).tobytes())   # from P0 content, shared by its perturbations
    bse, inlens, se = raw["BSE"], raw["Inlens"], raw["SE"]
    if pert in IMAGING_PERTS:
        bse, inlens, se = _perturb(bse, pert), _perturb(inlens, pert, seed=1), _perturb(se, pert, seed=2)
    elif pert in MATERIAL_INJECTS:
        bse, inlens = _inject(bse, inlens, H.harmonise_arrays(bse, inlens, se, seed), pert)
    elif pert != P0:
        raise ValueError(f"unknown perturbation {pert!r}")
    crop = make_crop(bse, inlens, se, pert, crop_id, seed)
    _atomic(path, lambda tmp: np.savez(tmp, bse=crop.raw["BSE"], inlens=crop.raw["Inlens"], se=crop.raw["SE"],
                                       anchors=json.dumps(crop.anchors), **{f"m_{k}": np.packbits(v) for k, v in crop.masks.items()}))
    return path


def load_crop(crop_id, pert=P0, build=True):
    path = views_path(crop_id, pert)
    if not path.exists():
        if not build:
            raise FileNotFoundError(path)
        build_views(crop_id, pert)
    z = np.load(path)
    n = WINDOW[0] * WINDOW[1]
    masks = {k[2:]: np.unpackbits(z[k], count=n).reshape(WINDOW).astype(bool) for k in z.files if k.startswith("m_")}
    return Crop({"BSE": z["bse"], "Inlens": z["inlens"], "SE": z["se"]}, json.loads(str(z["anchors"])), masks, pert, crop_id)


