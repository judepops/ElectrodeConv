@dataclass
class Crop:
    """One crop version: the common window of one site under one perturbation.

    raw       {"BSE", "Inlens", "SE"} -> uint8 (1336, 6944), channel 0 of the TIF, 8 edge columns trimmed
    anchors   black level and graphite level in raw grey levels, thresholds in graphite units, noise levels.
              These describe the imaging, not the material: a feature built on them must be tagged "imaging".
    masks     the phase maps and the valid mask, all bool (1336, 6944)
    pert      "P0" or the perturbation / injection applied to the raw image before harmonising
    """
    raw: dict
    anchors: dict
    masks: dict
    pert: str = P0
    _id: str = ""                                    # for the runner and diagnostics only; never read it in a family
    _cache: dict = field(default_factory=dict, repr=False)

    @property
    def shape(self):
        return WINDOW

    def view(self, det, view="anchored", scale=1):
        """One detector in one view, block-averaged by `scale` (1, 2, 4, 8).

        raw         uint8 grey levels as stored (after the perturbation)
        anchored    BSE in graphite units (0 = black level, 1 = graphite); Inlens and SE rank-normalised to 0..1.
                    No noise added: use it for intensity statistics and as model input.
        harmonised  anchored plus Gaussian noise up to one fixed level, so every crop is equally noisy.
                    Use it for fine texture (< 500 nm), where noise would otherwise mark the imaging session.
        smoothed    anchored blurred by sigma = 2.5 px. Use it for phase work, never for fine texture.
        """
        key = (det, view, scale)
        if key not in self._cache:
            base = (det, view, 1)
            if base not in self._cache:
                self._cache[base] = self._full(det, view)
            self._cache[key] = block_mean(self._cache[base], scale)
        return self._cache[key]

    def _full(self, det, view):
        if view == "raw":
            return self.raw[det]
        if view == "anchored":
            if det == "BSE":
                return (self.raw["BSE"].astype(np.float32) - np.float32(self.anchors["black"])) / np.float32(self.anchors["scale"])
            return H.rank_normalise(self.raw[det])
        if view == "harmonised":
            a = self.view(det, "anchored")
            target = {"BSE": H.CFG["noise"]["bse_target_sigma"]}.get(det, H.CFG["noise"]["inlens_target_sigma"])
            sigma = self.anchors["bse_noise_sigma"] if det == "BSE" else self.anchors["inlens_noise_sigma"]
            extra = float(np.sqrt(max(target ** 2 - sigma ** 2, 0.0)))
            if extra == 0.0:
                return a
            rng = np.random.default_rng(self.anchors["seed"] + DETECTORS.index(det) if det in DETECTORS else self.anchors["seed"] + 7)
            return a + rng.standard_normal(a.shape, dtype=np.float32) * np.float32(extra)
        if view == "smoothed":
            return ndi.gaussian_filter(self.view(det, "anchored"), SMOOTH_SIGMA_PX)
        raise ValueError(f"unknown view {view!r}: use one of {VIEWS}")

    def phase(self, name="void"):
        """A phase map (bool). void / bright are the decision recipe; the _lo and _hi versions move the threshold by
        VOID_BAND_G / BRIGHT_BAND_G graphite units so that a fraction can always be reported as lo / mid / hi.
        _lo is the stricter threshold (smaller phase), _hi the looser one. "graphite" is what is left: not void,
        not bright, not dim."""
        if name == "graphite":
            if "graphite" not in self._cache:
                self._cache["graphite"] = ~(self.masks["void"] | self.masks["bright"] | self.masks["dim"])
            return self._cache["graphite"]
        return self.masks[name]

    @property
    def valid(self):
        """False where the raw BSE is saturated (and 2 px around it). Exclude those pixels from statistics."""
        return self.masks["valid"]


def _phase_maps(h, raw_bse_window):
    """lo / mid / hi maps of the harmonised window."""
    seg = H.CFG["segmentation"]
    t_void, t_bright = h.acq["void_threshold"], h.acq["bright_threshold"]
    bright_blur = ndi.gaussian_filter(h.bse, seg["bright_blur_sigma_px"])

    def void_at(t):
        return H.fill_small_holes(H.drop_small(h.bse_blur < t, seg["min_void_px"]), seg["min_void_px"])

    maps = {"void": h.void, "void_lo": void_at(t_void - VOID_BAND_G), "void_hi": void_at(t_void + VOID_BAND_G),
            "bright": h.bright, "bright_lo": H._bright_mask(bright_blur, t_bright + BRIGHT_BAND_G),
            "bright_hi": H._bright_mask(bright_blur, t_bright - BRIGHT_BAND_G), "bright_fixed": h.bright_fixed, "dim": h.dim}
    maps = {k: np.ascontiguousarray(v) for k, v in maps.items()}
    maps["valid"] = ~ndi.binary_dilation(raw_bse_window == 255, iterations=2)
    return maps


def common_window(shape):
    """(r0, r1, x0, x1): the rows and columns of the common window inside a raw image of this shape.

    harmonise.crop_box picks the rows (250..H-25, then the central 1336) and trims 8 columns each side; the Crop keeps
    the central 6944 of the remaining columns.
    """
    r0, r1, c0, c1 = H.crop_box(*shape)
    if r1 - r0 < WINDOW[0] or c1 - c0 < WINDOW[1]:
        raise ValueError(f"image {tuple(shape)} is too small for the common window {WINDOW}")
    x0 = c0 + (c1 - c0 - WINDOW[1]) // 2
    return r0, r1, x0, x0 + WINDOW[1]


def make_crop(raw_bse, raw_inlens, raw_se=None, pert=P0, crop_id="", seed=None):
    """Raw images of one site (2D uint8, at least 1611 rows and 6960 columns) -> Crop.

    Anchors, noise levels, thresholds and phase maps are computed on exactly the pixels the Crop holds: harmonise is
    handed the common columns plus the 8 it trims on each side, and nothing else. So a Crop does not depend on the
    image width, on what lies outside the window, or on any name: the noise seed comes from the window's content.
    """
    se = raw_inlens if raw_se is None else raw_se
    r0, r1, x0, x1 = common_window(raw_bse.shape)
    side = H.CFG["crop"]["side_px"]
    window = {d: np.ascontiguousarray(img[r0:r1, x0:x1]) for d, img in (("BSE", raw_bse), ("Inlens", raw_inlens), ("SE", se))}
    if seed is None:
        seed = zlib.crc32(window["BSE"].tobytes())
    h = H.harmonise_arrays(*(img[:, x0 - side:x1 + side] for img in (raw_bse, raw_inlens, se)), seed)
    if h.shape != WINDOW:
        raise ValueError(f"harmonise returned {h.shape}, expected {WINDOW}")
    a = h.acq
    anchors = dict(black=float(a["bse_black_raw"]), graphite=float(a["bse_graphite_raw"]),
                   scale=float(max(a["bse_graphite_raw"] - a["bse_black_raw"], 1.0)),
                   bse_noise_sigma=float(a["bse_noise_sigma"]), inlens_noise_sigma=float(a["inlens_noise_sigma"]),
                   void_threshold=float(a["void_threshold"]), bright_threshold=float(a["bright_threshold"]),
                   bright_mode=float(a["bright_mode"]), bright_mode_found=bool(a["bright_mode_found"]),
                   has_se=raw_se is not None, seed=int(seed))
    return Crop(window, anchors, _phase_maps(h, window["BSE"]), pert, crop_id)


