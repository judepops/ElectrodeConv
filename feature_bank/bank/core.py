@dataclass
class FeatureResult:
    """scalars: name -> float.  blocks: name -> array, one per crop (embeddings, spectra, Gram matrices).
    tiles: name -> (n_tiles, d) array, for set kernels.  catalog: one dict per name, built by the three methods."""
    family: str
    scalars: dict = field(default_factory=dict)
    blocks: dict = field(default_factory=dict)
    tiles: dict = field(default_factory=dict)
    catalog: list = field(default_factory=list)
    meta: dict = field(default_factory=dict)       # how it was made (profile, device, precision, versions): kept in .done

    def _add(self, kind, det, view, scale_nm, stat, length_um, layer, tag):
        name = column(self.family, det, view, scale_nm, stat)
        self.catalog.append(dict(name=name, kind=kind, family=self.family, detector=det, view=view, scale_nm=int(scale_nm),
                                 length_um=np.nan if length_um is None else float(length_um), layer=str(layer), tag=tag))
        return name

    def scalar(self, det, view, scale_nm, stat, value, *, length_um=None, layer="", tag="material"):
        """One number. length_um = the physical length the statistic probes (e.g. a GLCM offset), None if it has none."""
        self.scalars[self._add("scalar", det, view, scale_nm, stat, length_um, layer, tag)] = float(value)

    def block(self, det, view, scale_nm, stat, array, *, length_um=None, layer="", tag="material", dtype=np.float32):
        self.blocks[self._add("block", det, view, scale_nm, stat, length_um, layer, tag)] = np.asarray(array, dtype)

    def tile_block(self, det, view, scale_nm, stat, array, *, length_um=None, layer="", tag="material", dtype=np.float32):
        """dtype=np.float16 halves the size of big arrays such as token grids."""
        self.tiles[self._add("tiles", det, view, scale_nm, stat, length_um, layer, tag)] = np.asarray(array, dtype)


def validate(res):
    """Raise ValueError listing every way a FeatureResult breaks the contract."""
    problems = []
    names = [c["name"] for c in res.catalog]
    if len(set(names)) != len(names):
        problems.append("duplicate names in the catalog")
    if set(names) != set(res.scalars) | set(res.blocks) | set(res.tiles):
        problems.append("catalog and values do not list the same names")
    for c in res.catalog:
        if c["tag"] not in TAGS:
            problems.append(f"{c['name']}: tag {c['tag']!r} is not one of {TAGS}")
        if c["detector"] in LEAKRISK_DETECTORS and c["tag"] != "leakrisk":
            problems.append(f"{c['name']}: anything from {c['detector']} must be tagged leakrisk")
        if c["name"].count("|") != 4 or not c["name"].startswith(res.family + "|"):
            problems.append(f"{c['name']}: name must be family|det|view|scale_nm|stat")
        bad = forbidden_tokens(c["name"])
        if bad:
            problems.append(f"{c['name']}: forbidden name part(s) {sorted(bad)}")
    for name, v in res.scalars.items():
        if not np.isfinite(v):
            problems.append(f"{name}: not finite ({v})")
    for name, v in {**res.blocks, **res.tiles}.items():
        if v.size == 0 or not np.isfinite(v).all():
            problems.append(f"{name}: empty or not finite")
    for name, v in res.tiles.items():
        if v.ndim != 2:
            problems.append(f"{name}: tile arrays must be (n_tiles, d), got {v.shape}")
    if problems:
        raise ValueError(f"{res.family}: " + "; ".join(problems[:12]) + (f" (+{len(problems) - 12} more)" if len(problems) > 12 else ""))


def feat_paths(family, crop_id, pert=P0):
    base = FEAT_DIR / family / pert / crop_id
    return base.with_suffix(".parquet"), base.with_suffix(".npz"), base.with_suffix(".done")


def save_result(res, crop_id, pert=P0, seconds=None):
    validate(res)
    parquet, npz, done = feat_paths(res.family, crop_id, pert)
    done.unlink(missing_ok=True)
    _atomic(parquet, lambda tmp: pd.DataFrame([res.scalars], dtype=np.float64).to_parquet(tmp))
    if res.blocks or res.tiles:
        _atomic(npz, lambda tmp: np.savez(tmp, **res.blocks, **res.tiles))
    _atomic(FEAT_DIR / res.family / "catalog.parquet", lambda tmp: pd.DataFrame(res.catalog).to_parquet(tmp))
    done.write_text(json.dumps(dict(n_scalars=len(res.scalars), n_blocks=len(res.blocks), n_tiles=len(res.tiles),
                                    seconds=None if seconds is None else round(seconds, 1), meta=res.meta), default=str))
    STATUS_LOG.parent.mkdir(parents=True, exist_ok=True)
    with open(STATUS_LOG, "a") as f:
        f.write(json.dumps(dict(t=time.strftime("%Y-%m-%dT%H:%M:%S"), family=res.family, pert=pert, crop=crop_id,
                                seconds=None if seconds is None else round(seconds, 1), n_scalars=len(res.scalars),
                                n_blocks=len(res.blocks), n_tiles=len(res.tiles))) + "\n")


def is_done(family, crop_id, pert=P0):
    return feat_paths(family, crop_id, pert)[2].exists()


def load_scalars(family, perts=(P0,), crops=None):
    """Every finished crop version of one family as a DataFrame indexed by (pert, crop). Missing ones are skipped."""
    rows = {}
    for pert in perts:
        for crop_id in crops or all_crops():
            parquet, _, done = feat_paths(family, crop_id, pert)
            if done.exists():
                frame = pd.read_parquet(parquet)
                rows[(pert, crop_id)] = frame.iloc[0] if len(frame) else pd.Series(dtype=float)   # block-only families
    return pd.DataFrame.from_dict(rows, orient="index") if rows else pd.DataFrame()


def load_arrays(family, crop_id, pert=P0):
    """{name: array} of one crop version's blocks and tile arrays ({} if the family has none)."""
    npz = feat_paths(family, crop_id, pert)[1]
    if not npz.exists():
        return {}
    with np.load(npz) as z:
        return {k: z[k] for k in z.files}


def load_catalog(family):
    return pd.read_parquet(FEAT_DIR / family / "catalog.parquet")
