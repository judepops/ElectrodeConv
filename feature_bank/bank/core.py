def crops_table():
    """meta/crops.csv: site, folder, source_image."""
    return pd.read_csv(META_DIR / "crops.csv")


def all_crops():
    return tuple(crops_table().site)


def crop_versions(crops="all", perts=P0):
    """Expand the shorthand used on the command line into (crop, pert) pairs."""
    ids = all_crops()
    names = {"all": ids, "smoke": SMOKE_CROPS, "inject": INJECT_CROPS}.get(crops, None) if isinstance(crops, str) else tuple(crops)
    if names is None:
        names = tuple(c for c in crops.split(",") if c)
    unknown = sorted(set(names) - set(ids))
    if unknown:
        raise ValueError(f"unknown crops {unknown}")
    kinds = {P0: (P0,), "imaging": IMAGING_PERTS, "inject": MATERIAL_INJECTS,
             "all": (P0,) + IMAGING_PERTS + MATERIAL_INJECTS}.get(perts, None) if isinstance(perts, str) else tuple(perts)
    if kinds is None:
        kinds = tuple(p for p in perts.split(",") if p)
    return [(c, p) for p in kinds for c in names if p not in MATERIAL_INJECTS or c in INJECT_CROPS]


