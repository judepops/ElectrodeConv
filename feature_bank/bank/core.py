# small image helpers every family shares
# ----------------------------------------------------------------------------------------------------
def block_mean(arr, factor):
    """Downsample by an integer factor with a block mean (no interpolation, so pixel size stays exact)."""
    if factor == 1:
        return arr
    h, w = (arr.shape[0] // factor) * factor, (arr.shape[1] // factor) * factor
    return arr[:h, :w].astype(np.float32).reshape(h // factor, factor, w // factor, factor).mean(axis=(1, 3))


def tiles(arr, size, stride=None):
    """(n, size, size) stack of tiles in a fixed order. Positions are deliberately not returned."""
    stride = stride or size
    ys = range(0, arr.shape[0] - size + 1, stride)
    xs = range(0, arr.shape[1] - size + 1, stride)
    return np.stack([arr[y:y + size, x:x + size] for y in ys for x in xs])


def quantise(arr, kind, levels):
    """Integer grey levels 0..levels-1 over the fixed global range of `kind` ("raw", "BSE", "Inlens", "SE")."""
    lo, hi = QUANT_RANGE[kind]
    q = np.floor((np.asarray(arr, np.float32) - lo) / (hi - lo) * levels)
    return np.clip(q, 0, levels - 1).astype(np.int32)


def column(family, det, view, scale_nm, stat):
    return f"{family}|{det}|{view}|{int(scale_nm)}|{stat}"


def forbidden_tokens(name):
    """The forbidden tokens in a column or block name (empty set = fine). Plural and numbered forms count too:
    tile_rows, fold3 and n_images are refused just like row, fold and image."""
    bad = set()
    for token in re.split(r"[^a-z0-9]+", name.lower()):
        stem = token.rstrip("0123456789")
        for form in (token, stem, stem[:-1] if stem.endswith("s") else "", stem[:-2] if stem.endswith("es") else "",
                     "index" if stem == "indices" else ""):
            if form in FORBIDDEN_TOKENS:
                bad.add(token)
    return bad


