"""The feature-bank contract: one Crop in, one FeatureResult out, written where the harness expects it.

FROZEN after Phase 0 (contract version 2, 3 Oct 23:xx: see bank/CONTRACT_REQUESTS.md for what changed). Ask for a
change in bank/CONTRACT_REQUESTS.md; do not edit this file from a family lane.

    from bank.core import Crop, FeatureResult, load_crop, tiles, block_mean, quantise

    FAMILY = "phase"                                   # bank/families/phase.py
    def extract(crop, cfg):
        res = FeatureResult(FAMILY)
        void = crop.phase("void")
        res.scalar("BSE", "phase", 25, "void_frac_mid", void.mean(), length_um=None, tag="material")
        return res

Run a family (2 smoke crops first, then every crop, then the perturbations):

    python -m bank.run fam phase --sites smoke --perts P0
    python -m bank.run fam phase --sites all --perts P0
    python -m bank.run fam phase --sites all --perts imaging

What a family may use: the Crop's views, phase maps, valid mask and helper functions below. Nothing else.
What no feature may ever see: image height or width, file or folder names, the crop id, which source image a
crop came from, tile positions, or anything in meta/analysis_only.csv. Those exist for splits, nulls and
diagnostics only. Every Crop has the same shape for that reason.

Layout under processed/bank/ (not in git):
    views/<pert>/<crop>.npz                  raw windows, phase maps and anchors of one crop version
    feat/<family>/<pert>/<crop>.parquet      one row of scalars, columns named family|det|view|scale_nm|stat
    feat/<family>/<pert>/<crop>.npz          high-dimensional blocks and per-tile arrays
    feat/<family>/<pert>/<crop>.done         written last: the crop version is complete
    feat/<family>/catalog.parquet            one row per column or block: what it is and how to treat it
    _status.jsonl                            one line per finished job
"""
